/** File: Generates exact declaration locations for reviewable self-documentation. Functions: walk, declarations, render, and main. Variables: SOURCE_ROOTS and patterns define the indexed code surface. */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const repository = resolve(import.meta.dirname, "..");
const sourceRoots = ["src", "tests", "web/src", "web/tests", "scripts", "migrations"];
const outputPath = resolve(repository, "docs/CODE_INDEX.md");
const accepted = /\.(?:rs|ts|mjs|sh|bats|sql)$/;
const patterns = [
  [/^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z0-9_]+)/, "function"],
  [/^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)/, "function"],
  [/^\s*(?:pub\s+)?(?:struct|enum|trait)\s+([A-Za-z0-9_]+)/, "type"],
  [/^\s*export\s+(?:interface|type)\s+([A-Za-z0-9_]+)/, "type"],
  [/^\s*(?:pub\s+)?const\s+([A-Za-z0-9_]+)/, "constant"],
  [/^\s*(?:export\s+)?const\s+([A-Za-z0-9_]+)/, "constant"],
  [/^([A-Za-z0-9_]+)\(\)\s*\{/, "function"],
  [/^CREATE TABLE IF NOT EXISTS\s+([A-Za-z0-9_]+)/i, "table"],
  [/^CREATE INDEX IF NOT EXISTS\s+([A-Za-z0-9_]+)/i, "index"]
];

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory() && !["node_modules", "target", "dist"].includes(entry.name)) files.push(...await walk(path));
    else if (entry.isFile() && accepted.test(entry.name)) files.push(path);
  }
  return files;
}

function declarations(text) {
  const found = [];
  for (const [offset, line] of text.split(/\r?\n/).entries()) {
    for (const [pattern, kind] of patterns) {
      const match = line.match(pattern);
      if (match?.[1]) { found.push({ kind, name: match[1], line: offset + 1 }); break; }
    }
  }
  return found;
}

async function render() {
  const files = (await Promise.all(sourceRoots.map(async (root) => walk(resolve(repository, root))))).flat();
  const sections = [];
  for (const file of files.sort()) {
    const rows = declarations(await readFile(file, "utf8"));
    if (!rows.length) continue;
    const path = relative(repository, file).replaceAll("\\", "/");
    sections.push(`## \`${path}\`\n\n| Kind | Name | Line |\n|---|---|---:|\n${rows.map((row) => `| ${row.kind} | \`${row.name}\` | ${row.line} |`).join("\n")}`);
  }
  return `# Code Index\n\nGenerated by \`npm run code-index\`. Line numbers refer to the committed source and are checked in CI. Local variables are described by each file header and kept close to use.\n\n${sections.join("\n\n")}\n`;
}

const generated = await render();
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== generated) throw new Error("docs/CODE_INDEX.md is stale; run npm run code-index");
} else {
  await writeFile(outputPath, generated, "utf8");
}

